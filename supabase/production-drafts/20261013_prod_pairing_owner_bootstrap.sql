-- PRODUCTION DRAFT — owner bootstrap for existing unowned boxes
-- Target: sodgzkablshladvbtnes (Precios al Día production).
-- Status: NOT APPLIED. Requires a verified backup, staging rehearsal, and explicit approval.
-- Depends on: 20261013_prod_pairing_token_owner_proof.sql (must be applied first or together).
-- Design draft only; not validated against a live database.
--
-- Problem: after the owner-proof draft, a box with owner_auth_id IS NULL can never
-- get a pairing token. This draft provides one reviewed path to bind an owner.
--
-- Proof of possession: the box displays a one-time claim code that is only shown
-- on the physical device (for example, on its local screen during first setup).
-- The owner submits that code while signed in. The server stores only its SHA-256
-- hash and accepts one successful claim per box. Codes expire and are single-use.
--
-- Rules:
--   * Claim requires an authenticated caller and a valid, unexpired, unused code.
--   * A box already owned by someone else is never reassigned by this path.
--   * Every attempt (success or failure) is audited with the caller and time.
--   * Codes are generated by the box itself; this draft does not create them.
--
-- Grant-neutral for existing objects. The new table and function are added;
-- no existing row is changed by this file except the explicit claim.

BEGIN;

CREATE TABLE IF NOT EXISTS public.device_owner_claims (
    id           bigserial PRIMARY KEY,
    primary_device_id text NOT NULL,
    claim_hash   text NOT NULL,
    expires_at   timestamptz NOT NULL,
    used_at      timestamptz,
    used_by      uuid,
    created_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.device_owner_claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_owner_claims FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.device_owner_claims FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS public.device_owner_claim_audit (
    id           bigserial PRIMARY KEY,
    primary_device_id text NOT NULL,
    caller_auth_id uuid,
    outcome      text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.device_owner_claim_audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_owner_claim_audit FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.device_owner_claim_audit FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.claim_box_owner(p_device_id text, p_claim_code text)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    v_owner uuid := auth.uid();
    v_device text := trim(p_device_id);
    v_hash text := encode(digest(upper(trim(p_claim_code)), 'sha256'), 'hex');
    v_claim public.device_owner_claims%ROWTYPE;
    v_row public.device_pairings%ROWTYPE;
BEGIN
    IF v_owner IS NULL THEN
        RETURN json_build_object('success', false, 'message', 'Sesión no autenticada.');
    END IF;

    SELECT * INTO v_row
    FROM public.device_pairings
    WHERE primary_device_id = v_device
    FOR UPDATE;

    IF NOT FOUND THEN
        INSERT INTO public.device_owner_claim_audit (primary_device_id, caller_auth_id, outcome)
        VALUES (v_device, v_owner, 'unknown_box');
        RETURN json_build_object('success', false, 'message', 'Caja no encontrada.');
    END IF;

    IF v_row.owner_auth_id IS NOT NULL THEN
        INSERT INTO public.device_owner_claim_audit (primary_device_id, caller_auth_id, outcome)
        VALUES (v_device, v_owner, 'already_owned');
        RETURN json_build_object('success', false, 'message', 'La caja ya tiene dueño.');
    END IF;

    SELECT * INTO v_claim
    FROM public.device_owner_claims
    WHERE primary_device_id = v_device
      AND claim_hash = v_hash
      AND used_at IS NULL
      AND expires_at > now()
    ORDER BY created_at DESC
    LIMIT 1
    FOR UPDATE;

    IF NOT FOUND THEN
        INSERT INTO public.device_owner_claim_audit (primary_device_id, caller_auth_id, outcome)
        VALUES (v_device, v_owner, 'invalid_or_expired_code');
        RETURN json_build_object('success', false, 'message', 'Código inválido o expirado.');
    END IF;

    UPDATE public.device_owner_claims
    SET used_at = now(), used_by = v_owner
    WHERE id = v_claim.id;

    UPDATE public.device_pairings
    SET owner_auth_id = v_owner
    WHERE id = v_row.id;

    INSERT INTO public.device_owner_claim_audit (primary_device_id, caller_auth_id, outcome)
    VALUES (v_device, v_owner, 'claimed');

    RETURN json_build_object('success', true, 'primary_device_id', v_device);
END;
$$;

REVOKE ALL ON FUNCTION public.claim_box_owner(text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.claim_box_owner(text, text) TO authenticated;

COMMIT;
